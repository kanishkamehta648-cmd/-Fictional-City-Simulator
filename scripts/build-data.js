// Copies data/city.json into src/city-data.js so index.html works when you
// simply double-click it (browsers block fetch() on file:// pages).
// Run after editing data/city.json:  node scripts/build-data.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const json = JSON.parse(fs.readFileSync(path.join(root, 'data', 'city.json'), 'utf8'));
const out = '// GENERATED by scripts/build-data.js from data/city.json. Do not edit by hand.\n' +
  'window.CITY_DATA = ' + JSON.stringify(json, null, 2) + ';\n';
fs.writeFileSync(path.join(root, 'src', 'city-data.js'), out);
console.log('wrote src/city-data.js');
